"""The checked-in FeatureExtraction SQL (step 4 parts 1 and 2; R9 stage 1).

Part 1: complete, rendered, in its folder's dialect. Part 2: it fits the build machinery (R5, R6):
it splits into statements, its scratch tables are created before use and dropped, Databricks scratch
tables render, and every OMOP table it reads is one the project always imports. All of it holds for
both modes: aggregated (`<connection>/`) and person (`<connection>/person/`, R9), whose analysis and
covariate ids equal the aggregated render's.

Reproducing it needs Java and the pinned jars, so that is `tools/render_feature_extraction.py --check`,
not a unit test.
"""
import importlib.util
import json
import os
import re
import unittest

import stubs

stubs.install()

from solution.recipes.sql_text import render_temp_tables, split_statements  # noqa: E402
from solution.setup.sql_dialect import DATABRICKS, REDSHIFT, SNOWFLAKE, detect_dialect  # noqa: E402
from solution.variables import MANDATORY_TABLES, MANDATORY_VOCABULARY  # noqa: E402

SQL_DIR = os.path.join(stubs.ROOT, "solution", "characterization", "sql")
FOLDER_DIALECT = {"snowflake": SNOWFLAKE, "databricks": DATABRICKS, "redshift": REDSHIFT}
TEMPLATE_SYNTAX = re.compile(r"\{\s*@|\}\s*\?\s*\{")  # SqlRender's {@x} ? {...} : {...}
# How each dialect names a scratch table: session temp tables (Snowflake, Redshift), Delta tables (R6).
SCRATCH = {"snowflake": r"\b(rwdfeatx\w+)", "redshift": r"#(\w+)", "databricks": r"@temp_database_schema\.(\w+)"}
CREATE = {"snowflake": r"CREATE\s+TEMP\s+TABLE\s+", "redshift": r"CREATE\s+TABLE\s+", "databricks": r"CREATE\s+TABLE\s+"}
DROP = r"DROP\s+TABLE\s+(?:IF\s+EXISTS\s+)?"
COMMENTS = re.compile(r"--[^\n]*|/\*.*?\*/", re.S)


def load_tool():
    path = os.path.join(stubs.ROOT, "tools", "render_feature_extraction.py")
    spec = importlib.util.spec_from_file_location("render_feature_extraction", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def mode_folders(tool):
    """(mode, connection folder, folder relative to SQL_DIR, {part: file}) for every rendered folder."""
    for mode, spec in tool.MODES.items():
        for folder in FOLDER_DIALECT:
            yield mode, folder, os.path.join(folder, spec["subfolder"]) if spec["subfolder"] else folder, spec["files"]


def sql_files(rel):
    return sorted(n for n in os.listdir(os.path.join(SQL_DIR, rel)) if n.endswith(".sql"))


def read(*parts):
    with open(os.path.join(SQL_DIR, *parts), encoding="utf-8", newline="") as fh:
        return fh.read()


class RenderedSql(unittest.TestCase):
    def setUp(self):
        self.tool = load_tool()
        self.manifest = json.loads(read("MANIFEST.json"))

    def test_manifest_matches_the_tool(self):
        self.assertEqual(self.manifest, self.tool.manifest())
        self.assertIn("VisitConceptCountLongTerm", self.manifest["presets"])
        self.assertNotIn("VisitConceptCountAnyTimePrior", self.manifest["presets"])  # no such preset
        # Dropped (owner, 2026-11-25): biased against a population with one year of history.
        self.assertFalse([p for p in self.manifest["presets"] if p.endswith("AnyTimePrior")])

    def test_both_modes_are_recorded(self):
        modes = self.manifest["modes"]
        self.assertEqual(sorted(modes), ["aggregated", "person"])
        self.assertTrue(modes["aggregated"]["aggregated"])
        self.assertFalse(modes["person"]["aggregated"])
        self.assertEqual(modes["person"]["row_id_field"], "row_id")
        # One scratch table per preset, each holding one of its analyses (R9 decision 7).
        self.assertEqual(len(modes["person"]["scratch_tables"]), len(self.manifest["presets"]))
        self.assertEqual(len(set(modes["person"]["scratch_tables"].values())), len(self.manifest["presets"]))

    def test_every_folder_has_every_part(self):
        self.assertEqual(sorted(os.listdir(SQL_DIR)), ["MANIFEST.json", "NOTICE", "databricks", "redshift", "snowflake"])
        for folder in FOLDER_DIALECT:
            self.assertEqual(sorted(os.listdir(os.path.join(SQL_DIR, folder))),
                             sorted(list(self.tool.PARTS.values()) + ["person"]))
        for _, _, rel, files in mode_folders(self.tool):
            self.assertEqual(sql_files(rel), sorted(files.values()), rel)

    def test_fully_rendered_with_only_the_documented_placeholders(self):
        for mode, folder, rel, files in mode_folders(self.tool):
            allowed = {"@cdm_database_schema", self.tool.MODES[mode]["cohort_table"]}
            if folder == "databricks":
                allowed.add("@temp_database_schema")
            for name in files.values():
                sql = read(rel, name)
                self.assertTrue(sql.startswith("-- Generated by tools/render_feature_extraction.py"), name)
                self.assertNotIn("\r", sql, name)
                self.assertIsNone(TEMPLATE_SYNTAX.search(sql), "%s/%s" % (rel, name))
                self.assertLessEqual(set(re.findall(r"@\w+", sql)), allowed, "%s/%s" % (rel, name))

    def test_construction_is_in_its_folders_dialect(self):
        for _, folder, rel, _ in mode_folders(self.tool):
            self.assertEqual(detect_dialect(read(rel, "construction.sql")), FOLDER_DIALECT[folder], rel)

    def test_omop_tables_read(self):
        # One fixed token for every OMOP table, vocabulary included; not the user's script naming.
        for _, _, rel, _ in mode_folders(self.tool):
            sql = read(rel, "construction.sql")
            self.assertEqual(set(re.findall(r"@cdm_database_schema\.(\w+)", sql)),
                             {"person", "observation_period", "visit_occurrence", "condition_era", "drug_era",
                              "concept", "concept_ancestor"}, rel)


class PersonMode(unittest.TestCase):
    """R9: the non-aggregated render writes the characterization's ids, one analysis per scratch table."""

    def setUp(self):
        self.tool = load_tool()

    def test_ids_equal_the_aggregated_render(self):
        for folder in FOLDER_DIALECT:
            aggregated = self.tool.id_signature(read(folder, "construction.sql"))
            person = self.tool.id_signature(read(folder, "person", "construction.sql"))
            self.assertEqual(len(aggregated[0]), 11, folder)
            self.assertEqual(sorted(aggregated[1]), [1, 2, 3, 4, 8, 9, 10, 210, 410, 901, 923], folder)
            self.assertEqual(person, aggregated, folder)

    def test_one_analysis_per_scratch_table(self):
        for folder in FOLDER_DIALECT:
            self.assertEqual(self.tool.person_tables(read(folder, "person", "construction.sql")),
                             self.tool.PERSON_TABLES, folder)

    def test_the_check_fails_on_a_changed_id(self):
        files = {}
        for _, _, rel, parts in mode_folders(self.tool):
            for name in parts.values():
                files[os.path.join(rel, name)] = read(rel, name)
        self.tool.check_modes(files)  # passes as checked in
        key = os.path.join("redshift", "person", "construction.sql")
        files[key] = files[key].replace("* 1000 + 210", "* 1000 + 211", 1)
        with self.assertRaises(SystemExit):
            self.tool.check_modes(files)

    def test_rows_are_written_per_entry(self):
        """Each scratch table keys its rows by the entry's row_id, read from the extraction cohort."""
        for folder in FOLDER_DIALECT:
            sql = read(folder, "person", "construction.sql")
            self.assertIn("@extraction_cohort cohort", sql, folder)
            self.assertIn("cohort.row_id", sql, folder)
            self.assertNotIn("@characterization_cohort", sql, folder)
            query = read(folder, "person", "query_covariates.sql")
            self.assertEqual(len(re.findall(r"cov_\d+\b", query)), 11, folder)


class FitsTheBuildMachinery(unittest.TestCase):
    """Part 2: what the characterization recipe (part 3) relies on."""

    def scratch(self, folder, pattern_prefix, sql):
        return {name.lower() for name in re.findall(pattern_prefix + SCRATCH[folder].lstrip("\\b"), sql, re.I)}

    def setUp(self):
        self.tool = load_tool()

    def test_statements_split(self):
        for _, _, rel, _ in mode_folders(self.tool):
            self.assertGreater(len(split_statements(read(rel, "construction.sql"))), 50, rel)
            self.assertGreater(len(split_statements(read(rel, "cleanup.sql"))), 10, rel)

    def test_each_result_query_is_one_select(self):
        """The recipes wrap each in `INSERT INTO <result table> (...)`."""
        for _, _, rel, files in mode_folders(self.tool):
            for name in files.values():
                if not name.startswith("query_"):
                    continue
                statements = split_statements(read(rel, name))
                self.assertEqual(len(statements), 1, "%s/%s" % (rel, name))
                self.assertEqual(COMMENTS.sub(" ", statements[0]).split()[0].upper(), "SELECT", "%s/%s" % (rel, name))

    def test_scratch_tables_are_created_before_use_and_all_dropped(self):
        for _, folder, rel, _ in mode_folders(self.tool):
            construction, cleanup = read(rel, "construction.sql"), read(rel, "cleanup.sql")
            created = self.scratch(folder, CREATE[folder], construction)
            self.assertGreater(len(created), 10, rel)
            used = set()
            for name in sql_files(rel):
                used |= {n.lower() for n in re.findall(SCRATCH[folder], read(rel, name), re.I)}
            self.assertEqual(used - created, set(), rel)
            dropped = self.scratch(folder, DROP, construction) | self.scratch(folder, DROP, cleanup)
            self.assertEqual(created - dropped, set(), "%s leaves scratch tables behind" % rel)

    def test_databricks_scratch_tables_render(self):
        for mode, _, rel, _ in mode_folders(self.tool):
            if not rel.startswith("databricks"):
                continue
            rendered, tables = render_temp_tables(read(rel, "construction.sql"), "Databricks",
                                                  "rwdtmp_sol__x_", "`catalog`.`scratch`")
            self.assertEqual(len(tables), len(set(tables)))
            self.assertTrue(all(t.startswith("`catalog`.`scratch`.`rwdtmp_sol__x_rwdfeatx") for t in tables))
            self.assertEqual(set(re.findall(r"@\w+", rendered)),
                             {"@cdm_database_schema", self.tool.MODES[mode]["cohort_table"]})

    def test_every_omop_table_read_is_always_imported(self):
        always = set(MANDATORY_TABLES + MANDATORY_VOCABULARY)
        for _, _, rel, _ in mode_folders(self.tool):
            for name in sql_files(rel):
                read_tables = set(re.findall(r"@cdm_database_schema\.(\w+)", read(rel, name)))
                self.assertEqual(read_tables - always, set(), "%s/%s" % (rel, name))


if __name__ == "__main__":
    unittest.main()
