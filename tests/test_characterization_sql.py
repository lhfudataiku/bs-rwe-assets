"""The checked-in FeatureExtraction SQL (step 4 part 1): complete, rendered, in its folder's dialect.

Reproducing it needs Java and the pinned jars, so that is `tools/render_feature_extraction.py --check`,
not a unit test. Part 2 adds the statement and placeholder checks against the build machinery.
"""
import importlib.util
import json
import os
import re
import unittest

import stubs

stubs.install()

from solution.setup.sql_dialect import DATABRICKS, REDSHIFT, SNOWFLAKE, detect_dialect  # noqa: E402

SQL_DIR = os.path.join(stubs.ROOT, "solution", "characterization", "sql")
FOLDER_DIALECT = {"snowflake": SNOWFLAKE, "databricks": DATABRICKS, "redshift": REDSHIFT}
TEMPLATE_SYNTAX = re.compile(r"\{\s*@|\}\s*\?\s*\{")  # SqlRender's {@x} ? {...} : {...}


def load_tool():
    path = os.path.join(stubs.ROOT, "tools", "render_feature_extraction.py")
    spec = importlib.util.spec_from_file_location("render_feature_extraction", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def read(*parts):
    with open(os.path.join(SQL_DIR, *parts), encoding="utf-8", newline="") as fh:
        return fh.read()


class RenderedSql(unittest.TestCase):
    def setUp(self):
        self.tool = load_tool()
        self.manifest = json.loads(read("MANIFEST.json"))

    def test_manifest_matches_the_tool(self):
        self.assertEqual(self.manifest, self.tool.manifest())
        self.assertIn("VisitConceptCountLongTerm", self.manifest["presets"])
        self.assertNotIn("VisitConceptCountAnyTimePrior", self.manifest["presets"])  # no such preset

    def test_every_folder_has_every_part(self):
        self.assertEqual(sorted(os.listdir(SQL_DIR)), ["MANIFEST.json", "NOTICE", "databricks", "redshift", "snowflake"])
        for folder in FOLDER_DIALECT:
            self.assertEqual(sorted(os.listdir(os.path.join(SQL_DIR, folder))), sorted(self.tool.PARTS.values()))

    def test_fully_rendered_with_only_the_documented_placeholders(self):
        for folder in FOLDER_DIALECT:
            allowed = {"@cdm_database_schema", "@characterization_cohort"}
            if folder == "databricks":
                allowed.add("@temp_database_schema")
            for name in self.tool.PARTS.values():
                sql = read(folder, name)
                self.assertTrue(sql.startswith("-- Generated by tools/render_feature_extraction.py"), name)
                self.assertNotIn("\r", sql, name)
                self.assertIsNone(TEMPLATE_SYNTAX.search(sql), "%s/%s" % (folder, name))
                self.assertLessEqual(set(re.findall(r"@\w+", sql)), allowed, "%s/%s" % (folder, name))

    def test_construction_is_in_its_folders_dialect(self):
        for folder, dialect in FOLDER_DIALECT.items():
            self.assertEqual(detect_dialect(read(folder, "construction.sql")), dialect, folder)

    def test_omop_tables_read(self):
        # One fixed token for every OMOP table, vocabulary included; not the user's script naming.
        for folder in FOLDER_DIALECT:
            sql = read(folder, "construction.sql")
            self.assertEqual(set(re.findall(r"@cdm_database_schema\.(\w+)", sql)),
                             {"person", "observation_period", "visit_occurrence", "condition_era", "drug_era",
                              "concept", "concept_ancestor"})


if __name__ == "__main__":
    unittest.main()
